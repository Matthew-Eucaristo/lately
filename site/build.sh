#!/usr/bin/env bash
# Assembles the GitHub Pages site into _site/ (or the directory given).
# Run from the repository root: site/build.sh [outdir]
# The interactive demo on the page is fed by lately itself: this script
# builds lately from the checkout and replays demo/sample (generic sample
# data, never this machine) into sample.js, the same way demo/setup.sh does
# for the recording. The recording is converted from demo/demo.gif; without
# ffmpeg the page falls back to the GIF itself.
set -euo pipefail
out=${1:-_site}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

rm -rf "$out"
mkdir -p "$out"
cp site/index.html site/style.css site/app.js site/favicon.svg site/og.png \
   site/404.html site/robots.txt site/sitemap.xml "$out"/
cp demo/demo.gif "$out"/demo.gif

# Replay the sample data with a throwaway HOME and baseline.
go build -trimpath -o "$tmp/lately" .
mkdir -p "$tmp/home"
run() { env HOME="$tmp/home" TZ=UTC NO_COLOR=1 LATELY_BASELINE="$tmp/baseline.json" "$tmp/lately" "$@"; }
run --replay demo/sample/seen --since 2d --list >/dev/null || true # primes the baseline, so NEW shows
run --replay demo/sample --json --min-level info --all >"$tmp/timeline.json" || true # exit 1/2 = findings
run why-restart --replay demo/sample --json >"$tmp/restart.json" || true
python3 -m json.tool "$tmp/timeline.json" >/dev/null
python3 -m json.tool "$tmp/restart.json" >/dev/null
{
  printf '// Generated by site/build.sh from lately --replay demo/sample. Sample data, not a real Mac.\n'
  printf 'window.LATELY_SAMPLE = {"timeline": '
  cat "$tmp/timeline.json"
  printf ', "restart": '
  cat "$tmp/restart.json"
  printf '};\n'
} >"$out/sample.js"

# Latest release tag, when tags are available (CI fetches them).
if tag=$(git describe --tags --abbrev=0 2>/dev/null); then
  sed -i.bak "s|<!--version-->[^<]*<!--/version-->|$tag|" "$out/index.html" && rm -f "$out/index.html.bak"
fi

if command -v ffmpeg >/dev/null; then
  ffmpeg -loglevel error -y -i demo/demo.gif -movflags +faststart -pix_fmt yuv420p \
    -vf "scale=trunc(iw/2)*2:trunc(ih/2)*2" -c:v libx264 -crf 24 -preset slow "$out/demo.mp4"
  ffmpeg -loglevel error -y -i demo/demo.gif -vf "select=eq(n\,90)" -frames:v 1 -c:v libwebp -quality 82 "$out/demo-poster.webp" || true
else
  echo "ffmpeg not found: the page will show demo.gif instead of a video" >&2
fi
ls -la "$out"
